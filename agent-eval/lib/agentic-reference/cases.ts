// Declarative registry of agentic-reference treatment/control cases. A case is
// pure data — an MCP URL or none, an agent, a model, overrides — resolved into
// an ExperimentConfig by agenticRefCaseExperiment. .agentic-ref/experiments/
// holds one generated stub per case; see
// scripts/generate-agentic-ref-experiments.mts.
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import type { ExperimentConfig } from '@vercel/agent-eval';
import type { EvalAgent, EvalIntegration, McpServerSpec } from '../templates.ts';
import { AGENT_NAME_PARTS, agenticRefExperiment } from './experiment.ts';

/** The full agentic-reference workflow list; every case runs all of them unless it pins its own `evals`. */
export const AGENTIC_REF_EVALS: string[] = [
	'701-new-ui-flow',
	'702-rework-ui-flow',
	'703-fix-bug-flow',
	'704-fix-a11y-flow',
	'705-migrate-to-ds-flow',
];

// The workflows that run against the Base UI-consuming app. The base-ui
// Storybook content variants only make sense as a treatment for these; the
// migration flow's design-system docs come from the Droppy Storybook instead.
const BASE_UI_APP_WORKFLOWS = AGENTIC_REF_EVALS.filter(
	(evalName) => evalName !== '705-migrate-to-ds-flow',
);

export interface AgenticRefCase {
	/** Kebab-case; becomes the experiment name and results dir (`agentic-ref-<name>`). */
	name: string;
	description: string;
	/** Present = run with this URL registered as an external design-system Storybook MCP. */
	storybookMcpUrl?: string;
	/** Sandbox flavor. Defaults to 'mcp' with a storybookMcpUrl, bare ('none') without. */
	integration?: EvalIntegration;
	/** Additional MCP servers to register, e.g. a component library's own server. */
	mcpServers?: Record<string, McpServerSpec>;
	/** Skill directories (relative to agent-eval/) installed into the agent's skills root. */
	skillDirs?: string[];
	/** Files written into the sandbox (path → content), e.g. an AGENTS.md docs pointer. */
	extraFiles?: Record<string, string>;
	/** Coding agent to evaluate. Default 'claude-code'. */
	agent?: EvalAgent;
	/** Workflow evals to run. Defaults to AGENTIC_REF_EVALS. */
	evals?: string[];
	overrides?: Partial<ExperimentConfig>;
}

// The design-system repo's Chromatic app id — the prefix of its build
// permalinks (`<appId>-<buildHash>.chromatic.com`).
const DESIGN_SYSTEM_CHROMATIC_APP_ID = '6a4e68f187e29b2ced28b17e';

// Chromatic branch permalink: non-alphanumeric characters in the branch name
// collapse to dashes. Unlike build permalinks these are mutable — they always
// serve the branch's latest published build — so a run's exact Storybook is
// pinned by `analysis.externalRepo`/`analysis.case`, not by this URL.
function chromaticBranchPermalink(branchName: string): string {
	const sanitized = branchName.replace(/[^a-zA-Z0-9]+/g, '-');
	return `https://${sanitized}--${DESIGN_SYSTEM_CHROMATIC_APP_ID}.chromatic.com`;
}

// Content-filter variants of the design-system Storybook, one per
// `experiment/*` branch regenerated by the design-system repo's
// storybook-freeze CLI (experiments.config.ts is the source of truth for
// branch names and their facet lists). Every branch expands into one case per
// agent in VARIANT_AGENTS, named `<agent>-<branch minus prefix>-<model>`.
const EXPERIMENT_BRANCHES = [
	'experiment/showcase-only',
	'experiment/api-reference',
	'experiment/keep-all',
	'experiment/purge-component-jsdoc',
	'experiment/purge-props-jsdoc',
] as const;

const VARIANT_AGENTS: EvalAgent[] = ['claude-code'];

function storybookVariantCases(): AgenticRefCase[] {
	return EXPERIMENT_BRANCHES.flatMap((branchName) => {
		const variant = branchName.replace(/^experiment\//, '');
		return VARIANT_AGENTS.map((agent) => {
			const { prefix, modelSuffix } = AGENT_NAME_PARTS[agent];
			return {
				name: `${prefix}-${variant}-${modelSuffix}`,
				description: `Design-system Storybook MCP, content variant "${variant}".`,
				storybookMcpUrl: chromaticBranchPermalink(branchName),
				agent,
				evals: BASE_UI_APP_WORKFLOWS,
			};
		});
	});
}

