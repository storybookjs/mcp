// Declarative registry of agentic-reference treatment/control cases. A case is
// pure data — a design-system MCP package or URL or none, an agent, a model,
// overrides — resolved into an ExperimentConfig by agenticRefCaseExperiment.
// .agentic-ref/experiments/ holds one generated stub per case; see
// scripts/generate-agentic-ref-experiments.ts.
import { existsSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

import type { ExperimentConfig } from '@vercel/agent-eval';
import type { EvalAgent, EvalIntegration, McpServerSpec } from '../templates.ts';
import { AGENT_NAME_PARTS, agenticRefExperiment } from './experiment.ts';
import type { StorybookMcpPackageSpec } from './local-mcp.ts';
import { resolveEvalSelection } from './selection.ts';

/** The active eval list; every case runs all of them unless it specifies its own `evals`. */

export const AGENTIC_REF_EVAL_REGISTRY: string[] = [
	'701-new-ui-flow',
	'702-rework-ui-flow',
	'703-fix-bug-flow',
	'704-fix-a11y-flow',
	// Parked for later.
	// '705-migrate-to-ds-flow',
	'706-new-ui-scheduled-flow',
];

// The workflows the Storybook content variants treat; the migration flows are
// excluded.
const DS_APP_WORKFLOWS = AGENTIC_REF_EVAL_REGISTRY.filter(
	(evalName) => !['705-migrate-to-ds-flow'].includes(evalName),
);

export interface AgenticRefCase {
	/** Kebab-case; becomes the experiment name and results dir (`agentic-ref-<name>`). */
	name: string;
	description: string;
	/** Present = run with this URL registered as an external design-system Storybook MCP. */
	storybookMcpUrl?: string;
	/**
	 * Present = serve the design-system Storybook MCP locally in the sandbox from
	 * this pkg.pr.new preview package. Mutually exclusive with storybookMcpUrl.
	 */
	storybookMcpPackage?: StorybookMcpPackageSpec;
	/** Sandbox flavor. Defaults to 'mcp' with an MCP package or URL, bare ('none') without. */
	integration?: EvalIntegration;
	/** Additional MCP servers to register, e.g. a component library's own server. */
	mcpServers?: Record<string, McpServerSpec>;
	/** Skill directories (relative to agent-eval/) installed into the agent's skills root. */
	skillDirs?: string[];
	/**
	 * Rewrites each eval's PROMPT.md before the agent runs, e.g. to append a
	 * docs pointer. Build appenders with appendToPrompt.
	 */
	editPrompt?: (prompt: string) => string;
	/** Coding agent to evaluate. Default 'claude-code'. */
	agent?: EvalAgent;
	/** Workflow evals to run. Defaults to AGENTIC_REF_EVAL_REGISTRY. */
	evals?: string[];
	overrides?: Partial<ExperimentConfig>;
}

// The design-system repo's MCP preview package: its storybook-mcp-preview
// workflow publishes @droppy/mcp (the repo's MCP server with the branch's
// Storybook manifests baked in) to pkg.pr.new on every push to experiment/*.
// Cases select a branch; setup pins its head sha, so each experiment runs
// against one immutable build — unlike the Chromatic branch permalinks these
// cases previously pointed at.
//
// The fixtures under evals/ pin a MealDrop built on Droppy, so the served
// documentation has to be Droppy's: an agent handed another system's docs finds
// nothing installed under those names and falls back to reading source.
const DROPPY_MCP_PACKAGE = {
	repo: 'yannbf/droppy-ds',
	packageName: '@droppy/mcp',
} as const;

function droppyMcpPackage(branch: string): StorybookMcpPackageSpec {
	return { ...DROPPY_MCP_PACKAGE, branch };
}

/** Build a case `editPrompt` that appends eval-specific context after the fixture's task prompt. */
function appendToPrompt(context: string): (prompt: string) => string {
	return (prompt) => `${prompt.trimEnd()}\n\n${context.trim()}\n`;
}

// Content-filter variants of the design-system Storybook, one per
// `experiment/*` branch regenerated by the design-system repo's
